/** Calls `dot(x, y)` for every lit pixel of `text` in the 3x5 font (4px advance). */
export function eachTextPixel(text: string, dot: (x: number, y: number) => void) {
  let cx = 0
  for (const ch of text.toUpperCase()) {
    const g = glyphs[ch] ?? glyphs[' ']!
    for (let i = 0; i < 15; i++) if (g[i] === '1') dot(cx + (i % 3), Math.floor(i / 3))
    cx += 4
  }
}
export const textWidth = (text: string) => Math.max(0, text.length * 4 - 1)
