export function tileSprite(theme: ThemeId, tile: Exclude<TileSprite, 'void'>, variant: 'face' | 'top' | 'alt' | 'plain' = 'plain'): Px {
  if (tile === 'floor') return pick(variant === 'alt' ? floorAlt : floor, theme)
  if (tile === 'wall') return pick(variant === 'top' ? wallTop : variant === 'alt' ? wallAlt : wall, theme)
  return tiles[tile]
}
export function actorSprite(theme: ThemeId, actor: ActorSprite): Px {
  if (actor === 'hero') return pick(hero, theme)
  if (actor === 'grunt') return pick(grunt, theme)
  if (actor === 'boss') return pick(boss, theme)
  return actor === 'brute' ? brute : actor === 'ranged' ? ranged : swarm
}
export const itemSprite = (item: ItemSprite): Px => items[item]
const pick = (t: Themed, theme: ThemeId) => t[theme] ?? t.base

/** Resolve a pixel char to a colour. `shift` remaps tones (dim, flash, cycle). */
export function colour(ch: string, p: Palette, mode: Mode = 'n', phase = 0): string | null {
  if (ch === '.') return null
  if (mode === 'f') return ch === '0' ? p.bg : ch === '1' ? p.mid : p.light
  if (mode === 'd') return ({ '0': p.bg, '1': p.dark, '2': p.dark, '3': p.mid, a: p.mid } as Record<string, string>)[ch] ?? null
  if (mode === 'c') {
    // Palette cycling: rotate mid -> light -> accent.
    const ring = [p.mid, p.light, p.accent]
    const i = { '2': 0, '3': 1, a: 2 }[ch]
    if (i !== undefined) return ring[(i + phase) % 3]!
  }
  return ({ '0': p.bg, '1': p.dark, '2': p.mid, '3': p.light, a: p.accent } as Record<string, string>)[ch] ?? null
}
export type Mode = 'n' | 'd' | 'f' | 'c'

